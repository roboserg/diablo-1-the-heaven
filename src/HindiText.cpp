// size: 0 = small, 1 = mid, 2 = big. Out-of-range cells fall back to the fixed
// cell width, which is what an unbuilt or mismatched pack would produce anyway.
int HIN_Advance( int cell, int size )
{
	if( cell < 0 || cell >= HIN_CELL_MAX )
		return size == 2 ? HIN_CELL_W_BIG : size == 1 ? HIN_CELL_W_MID : HIN_CELL_W_SMALL;
	const unsigned char w = ( size == 2 ) ? HIN_AdvBig[ cell ]
	                      : ( size == 1 ) ? HIN_AdvMid[ cell ]
	                                      : HIN_AdvSmall[ cell ];
	if( w == 0 )
		return size == 2 ? HIN_CELL_W_BIG : size == 1 ? HIN_CELL_W_MID : HIN_CELL_W_SMALL;
	return (int)w;
}
