//  WHY THIS FILE EXISTS. ChiNextSmall/Mid/Big hand back a FIXED cell width for any
//  double-byte pair, which is right for Chinese, Japanese and Korean because those
//  scripts really are monospaced. Devanagari is not. A bare consonant is ~13px of
//  ink where a conjunct carrying a left matra is ~21px, and a flat 22px step spaces
//  the letters so far apart that the gap inside a word matches the gap between
//  words -- the reader loses word boundaries, and the headline (shirorekha) that is
//  supposed to bind a word into one unit cannot reach its neighbour.
//
//  So Hindi needs the same treatment Arabic already has: a real advance per cell.
//  Unlike Arabic there is still NO shaping here -- the tables are pre-shaped, this
//  is only how wide each pre-composed cluster is.
//
//  GENERATED, NOT HAND-WRITTEN. These come from the same render that produced the
//  art in TH4loc_hin.mor, so the two must always be rebuilt together. A mismatch
//  shows up as text that overlaps or drifts apart, not as a crash.
//
//  Index is the sheet cell, i.e. ChiLetterID(lead,trail) - HIN_FIRST_ID.
// =============================================================================
